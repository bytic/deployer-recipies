<?php

declare(strict_types=1);

namespace Deployer;

task('deploy:cleanup:node', static function (): void {

    if (!test('[ -d {{deploy_path}}/current/node_modules ]')) {
        return;
    }

    $sudo = get('cleanup_use_sudo', false) ? 'sudo ' : '';
    run($sudo . 'rm -rf ' . quote('{{deploy_path}}/current/node_modules'));
});

task('deploy:previous_release:cleanup_node', static function (): void {
    if (!has('previous_release')) {
        return;
    }
    if (!test('[ -d {{previous_release}}/node_modules ]')) {
        return;
    }

    $sudo = get('cleanup_use_sudo', false) ? 'sudo ' : '';
    run($sudo . 'rm -rf ' . quote('{{previous_release}}/node_modules'));
});
